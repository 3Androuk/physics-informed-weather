"""Regenerate docs/forecast_demo_results.md from results_t2m/forecast_*.json.

Re-run after every arm lands (or via make_forecast_md.sh, which also commits):
    python -m eval.forecast_results_md
"""
import glob
import json
import os
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results_t2m"
OUT = ROOT / "docs" / "forecast_demo_results.md"

MODEL = {
    "diffusion": "Guided diffusion (no geo)",
    "diffusion_geo": "Guided diffusion (geo hash)",
    "diffusion_geo_combo": "Guided diffusion (geo hash + static)",
    "diffusion_geo_static": "Guided diffusion (static only)",
    "flow_matching": "Flow matching (no geo)",
    "flow_matching_geo": "Flow matching (geo hash)",
    "stochastic_interpolant": "Stochastic interpolant (no geo)",
    "residual_lm": "Residual diffusion (meanmap + residual)",
    "directmap": "Direct map",
}
# Legacy files written before the output stem encoded the arm.
LEGACY_ARM = {("24", "diffusion"): "ddnmplus0.112", ("120", "diffusion"): "ddnm"}
# Rows whose JSON was overwritten before the stem fix; values from the run log.
LOG_ONLY = [
    {"lead": "24", "ckpt": "diffusion", "arm": "ddnm", "eta": 0.0, "ens": 4,
     "fcst": 1.2165, "bicubic": 1.2630, "control": 0.7575, "crps": None,
     "spec": None, "note": "JSON overwritten by the DDNM+ arm; values from log"},
]
ARM_ORDER = {"ddnm": 0, "ddnmplus": 1, "noproj": 2}


def arm_label(arm):
    if arm == "ddnm":
        return "DDNM (λ=1)"
    if arm.startswith("ddnmplus"):
        return f"DDNM+ (σ_y={arm[len('ddnmplus'):]})"
    if arm == "noproj":
        return "no projection (λ=0)"
    return arm


def parse(path):
    d = json.loads(Path(path).read_text())
    stem = Path(path).stem  # forecast_24h_<ckpt>[_arm]
    m = re.match(r"forecast_(\d+)h_(.*)$", stem)
    lead, rest = m.group(1), m.group(2)
    arm = None
    me = re.search(r"_eta[0-9.]+$", rest)      # strip the eta suffix first
    if me:
        rest = rest[: me.start()]
    for a in ("noproj", "ddnm"):
        if rest.endswith("_" + a):
            arm, rest = a, rest[: -len(a) - 1]
            break
    mm = re.search(r"_(ddnmplus[0-9.]+)$", rest)
    if arm is None and mm:
        arm, rest = mm.group(1), rest[: mm.start()]
    if arm is None:
        arm = LEGACY_ARM.get((lead, rest), "ddnm")
    r = d["rmse_latweighted"]
    ch = next(iter(r["fcst"]))
    return {"lead": lead, "ckpt": rest, "arm": arm, "eta": d.get("eta", 0.0),
            "ens": d.get("ensemble"), "n": d.get("n_inits"),
            "fcst": r["fcst"][ch], "bicubic": r["bicubic"][ch],
            "control": r.get("control", {}).get(ch),
            "crps": d.get("crps_display"), "spec": d.get("spectrum_log_l1_display"),
            "note": ""}


def fmt(x, p=4):
    return "—" if x is None else f"{x:.{p}f}"


def pct(a, b):
    return "—" if (a is None or b is None or b == 0) else f"{100 * (a - b) / b:+.1f}%"


def status_lines():
    out = []
    for log in sorted(p for p in glob.glob(str(ROOT / "logs_fcst_*.log")) if "download" not in p):
        name = os.path.basename(log)[len("logs_fcst_"):-4]
        txt = Path(log).read_text(errors="ignore")
        if "ALLDONE" in txt:
            st = "done"
        elif "Traceback" in txt or "OutOfMemory" in txt:
            st = "FAILED (see log)"
        else:
            lead = re.findall(r"lead (\d+)h", txt)
            init = re.findall(r"init (\d+)/(\d+)", txt)
            st = (f"running — lead {lead[-1]}h, init {init[-1][0]}/{init[-1][1]}"
                  if lead and init else "queued")
        out.append(f"- `{name}`: {st}")
    return out


def main():
    rows = [parse(p) for p in glob.glob(str(RES / "forecast_*.json"))]
    rows += LOG_ONLY
    native = {re.search(r"native_hres_(\d+)h", p).group(1): json.loads(Path(p).read_text())
              for p in glob.glob(str(RES / "native_hres_*.json"))}
    leads = sorted({r["lead"] for r in rows}, key=int)

    L = []
    L.append("# NWP forecast downscaling demo — results\n")
    L.append(f"_Auto-generated by `eval/forecast_results_md.py` on "
             f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}. Re-run it after "
             f"each arm lands; do not edit the tables by hand._\n")
    L.append("## Setup\n")
    L.append("- **Input:** IFS HRES disseminated at **1.5°** (WeatherBench2, "
             "`hres/2016-2022-0012-240x121_..._conservative.zarr`), 2m temperature, "
             "inits 2016–2017 (the project's test years), stride 14 days → 53 inits; "
             "**8 inits scored** per arm.")
    L.append("- **Target:** ERA5 at **0.25°** on the ±60° band → **ratio 6** "
             "(non-dyadic; zero-shot for guided models, off-distribution for "
             "transports trained on {2,4,8}).")
    L.append("- **Reference (expensive path):** the *same* HRES run disseminated at "
             "0.25° (`hres/2016-2022-0012-1440x721.zarr`), scored by "
             "`eval/score_native_hres.py` on identical fields. HRES 1.5° is a "
             "conservative regrid of it, so it is the ceiling the cheap path tries to recover.")
    L.append("- **Sampler:** 4 members per init (sampler noise; HRES is one realization "
             "→ ensemble spans *downscaling* uncertainty only), tile 144 "
             "(128 % 6 ≠ 0), η per row. RMSE is cos(lat)-weighted (WB2 convention) "
             "on the **4-member ensemble mean**. CRPS is the fair estimator on the "
             "display channel. `control` = the same model fed the *coarsened truth* "
             "(isolates downscaling error from forecast error).")
    L.append("- CRPS of a deterministic field equals its MAE, so native and bicubic "
             "CRPS are their MAE.\n")

    for lead in leads:
        nat = native.get(lead)
        L.append(f"## Lead {lead} h\n")
        L.append("| model | consistency | η | ens | fcst RMSE (K) | Δ vs bicubic | Δ vs native | control RMSE | CRPS | Δ CRPS vs native | spectrum |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
        if nat:
            nrmse, nmae = nat["native_rmse_latweighted"], nat["native_mae_latweighted"]
            L.append(f"| **Native HRES 0.25° (expensive path)** | — | — | 1 | **{nrmse:.4f}** | "
                     f"{pct(nrmse, nat['bicubic_rmse_latweighted'])} | — | — | {nmae:.4f} (MAE) | — | — |")
            L.append(f"| Bicubic from 1.5° | — | — | 1 | {nat['bicubic_rmse_latweighted']:.4f} | — | "
                     f"{pct(nat['bicubic_rmse_latweighted'], nrmse)} | — | "
                     f"{nat['bicubic_mae_latweighted']:.4f} (MAE) | "
                     f"{pct(nat['bicubic_mae_latweighted'], nmae)} | — |")
        else:
            nrmse = nmae = None
        sub = [r for r in rows if r["lead"] == lead]
        sub.sort(key=lambda r: (r["fcst"], ARM_ORDER.get(r["arm"].rstrip("0123456789."), 9)))
        for r in sub:
            name = MODEL.get(r["ckpt"], r["ckpt"])
            note = f" _({r['note']})_" if r.get("note") else ""
            L.append(f"| {name}{note} | {arm_label(r['arm'])} | {r['eta']:g} | {r['ens']} | "
                     f"{fmt(r['fcst'])} | {pct(r['fcst'], r['bicubic'])} | {pct(r['fcst'], nrmse)} | "
                     f"{fmt(r['control'])} | {fmt(r['crps'])} | {pct(r['crps'], nmae)} | {fmt(r['spec'])} |")
        if nat:
            best = min((r for r in sub if r["arm"] == "ddnm"), key=lambda r: r["fcst"], default=None)
            if best:
                gap_b = nat["bicubic_rmse_latweighted"] - nrmse
                closed = (nat["bicubic_rmse_latweighted"] - best["fcst"]) / gap_b if gap_b else 0
                L.append(f"\nBest DDNM arm ({MODEL.get(best['ckpt'], best['ckpt'])}, η={best['eta']:g}) "
                         f"recovers **{100*closed:.0f}%** of the bicubic→native gap and sits "
                         f"**{pct(best['fcst'], nrmse)}** from the native product on RMSE.")
        L.append("")

    L.append("## Reading guide\n")
    L.append("- **Cost-benefit, not superiority.** The 1.5° product is 36× smaller than 0.25° "
             "(240×121 vs 1440×721). Native still wins RMSE; the cheap path recovers most of the "
             "bicubic→native gap and beats native on CRPS. Both products come from the *same* 9 km run, "
             "so this is a **dissemination/bandwidth** saving, not a compute saving.")
    L.append("- **Two CRPS wins.** vs bicubic from the *identical* 1.5° input (pure model contribution), "
             "and vs native 0.25° from 36× less input. A deterministic baseline has zero spread by "
             "construction, so the definitive probabilistic test is IFS ENS 0.25° vs IFS ENS 1.5° + downscaling.")
    L.append("- **Consistency is metric-dependent** (no-geo arms): DDNM (λ=1) wins RMSE; dropping the "
             "projection (λ=0) wins CRPS at long lead because the hard projection pins every member to the "
             "same erroneous coarse field. DDNM+ (λ_t) is a null: forecast error is *structured* and lives in "
             "the range space.")
    L.append("- **Transports at ratio 6:** trained on the discrete set {2,4,8}, so 6 is still off-distribution; "
             "both lose to guided diffusion on the control, SI badly.")
    L.append("- **Residual diffusion** is projected once on the *composed* field (per its original "
             "`reconstruct_residual`), not per step — not strictly like-for-like on consistency.\n")
    infl = sorted(glob.glob(str(RES / "members" / "*" / "inflation_*h.json")))
    if infl:
        L.append("## Variance inflation (post-processing, no resampling)\n")
        L.append("`x_i ← μ + α(x_i − μ)`: ensemble mean, RMSE and spectrum unchanged; "
                 "deviations already lie in ker A so consistency is preserved. Raw ensembles span "
                 "*downscaling* uncertainty only, hence the small spread/reliable ratios. "
                 "α* is in-sample (oracle); the cross-lead column applies the OTHER lead's α*.\n")
        L.append("| arm | lead | raw CRPS | spread/reliable (raw) | α* | CRPS at α* | Δ vs raw | Δ vs native (MAE) | calibrated α | cross-lead α → CRPS |")
        L.append("|---|---|---|---|---|---|---|---|---|---|")
        by_arm = {}
        for f in infl:
            d = json.loads(Path(f).read_text()); arm = Path(f).parent.name
            by_arm.setdefault(arm, {})[str(d["lead_h"])] = d
        for arm, leads_d in sorted(by_arm.items()):
            for lead, d in sorted(leads_d.items(), key=lambda kv: int(kv[0])):
                rows_ = {r["alpha"]: r for r in d["rows"]}
                raw = rows_[1.0]
                other = [v for k, v in leads_d.items() if k != lead]
                xl = "—"
                if other:
                    oa = other[0]["oracle_alpha"]
                    if oa in rows_:
                        xl = f"α={oa:g} → {rows_[oa]['crps']:.4f} ({pct(rows_[oa]['crps'], raw['crps'])})"
                nmae = native.get(lead, {}).get("native_mae_latweighted")
                L.append(f"| {arm} | {lead} h | {raw['crps']:.4f} | {raw['spread_ratio']:.2f} | "
                         f"{d['oracle_alpha']:g} | **{d['oracle_crps']:.4f}** | "
                         f"{pct(d['oracle_crps'], raw['crps'])} | {pct(d['oracle_crps'], nmae)} | "
                         f"{d['calibrated_alpha']:g} | {xl} |")
        L.append("")
    L.append("## Arm status (from `logs_fcst_*.log`)\n")
    L += status_lines()
    L.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT} ({len(rows)} rows, leads {leads})")


if __name__ == "__main__":
    main()
